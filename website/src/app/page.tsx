/**
 * Home page - Calendar view
 * Displays monthly calendar with clickable dates that have diary entries
 * Server component that fetches available dates on load
 */

import { CalendarGrid } from "@/components/CalendarGrid";
import { generateCalendarMonth } from "@/lib/date-utils";

/**
 * Fetch available diary dates from API
 * In production, consider caching strategy for performance
 */
async function getAvailableDates(): Promise<Set<string>> {
  try {
    // Use absolute URL in production, relative in development
    const baseUrl = process.env.NEXT_PUBLIC_BASE_URL || "http://localhost:3000";
    const response = await fetch(`${baseUrl}/api/diary/dates`, {
      cache: "no-store", // Ensure fresh data on each page load
    });

    if (!response.ok) {
      console.error("Failed to fetch available dates");
      return new Set();
    }

    const { data } = await response.json();
    return new Set(data);
  } catch (error) {
    console.error("Error fetching available dates:", error);
    return new Set();
  }
}

export default async function Home() {
  const today = new Date();
  const currentYear = today.getFullYear();
  const currentMonth = today.getMonth();

  const datesWithEntries = await getAvailableDates();

  const initialCalendar = generateCalendarMonth(
    currentYear,
    currentMonth,
    datesWithEntries
  );

  return (
    <div className="container mx-auto px-4 py-12 lg:py-16">
      <div className="max-w-5xl mx-auto">
        {/* Page introduction */}
        <div className="mb-12 text-center">
          <h1 className="text-4xl md:text-5xl font-bold text-text-primary dark:text-dark-text-primary mb-4">
            World Diary Archive
          </h1>
          <p className="text-lg text-text-secondary dark:text-dark-text-secondary max-w-2xl mx-auto">
            Select a date to read the AI-generated daily snapshot. Each entry
            synthesizes global events across politics, markets, entertainment,
            and culture.
          </p>
        </div>

        {/* Calendar grid */}
        <CalendarGrid
          initialMonth={initialCalendar}
          datesWithEntries={datesWithEntries}
        />

        {/* Information panel */}
        <div className="mt-12 bg-bg-secondary dark:bg-dark-bg-secondary border border-border dark:border-dark-border rounded-lg p-6">
          <h3 className="text-lg font-semibold text-text-primary dark:text-dark-text-primary mb-3">
            About This Project
          </h3>
          <div className="text-sm text-text-secondary dark:text-dark-text-secondary space-y-2">
            <p>
              Daily World Diary is an experimental automated journalism project
              that uses AI agents to generate comprehensive daily snapshots of
              world events. Each entry is produced by specialized agents
              focusing on different domains.
            </p>
            <p>
              The system operates autonomously, gathering information,
              analyzing trends, and synthesizing insights without human
              editorial intervention. All agent prompts are displayed at the
              bottom of each entry for transparency.
            </p>
            <p className="text-text-muted dark:text-dark-text-muted italic">
              Note: This is a demonstration using mocked data. In production,
              entries would be generated by a LangGraph-based backend with real
              data sources.
            </p>
          </div>
        </div>
      </div>
    </div>
  );
}
